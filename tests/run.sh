#!/usr/bin/env bash
# Headless logic test. No Roblox Studio needed:
#   1. inline the pure modules (Config, Board, EffectService) as globals, with a Vector3 stub
#   2. run tests/assertions.luau in the Luau CLI
#
# Usage: bash tests/run.sh          (override the binary with LUAU=/path/to/luau)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LUAU="${LUAU:-/opt/luau/luau}"
OUT="${TMPDIR:-/tmp}/rollrush_logic_test.luau"

python3 - "$ROOT" "$OUT" <<'PY'
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])

MODULES = [
    "src/shared/Config.luau",
    "src/shared/Board.luau",
    "src/server/EffectService.luau",
]

# Roblox-only requires and service lookups: the injected globals replace them.
SKIP = re.compile(r"^\s*local\s+\w+\s*=\s*(require\(|game:GetService\()")

parts = ["""-- GENERATED by tests/run.sh -- edit the modules, not this file.
Vector3 = { new = function(x, y, z) return { X = x, Y = y, Z = z } end }
"""]

for rel in MODULES:
    text = (root / rel).read_text()
    match = re.search(r"^return\s+(\w+)\s*$", text, re.M)
    if not match:
        raise SystemExit(f"{rel}: no top-level `return <name>` to promote")
    name = match.group(1)

    lines = []
    promoted = False
    for line in text.splitlines():
        if SKIP.match(line):
            continue
        if re.match(rf"^return\s+{name}\s*$", line):
            continue
        # Turn the module's own table into a global so later chunks can see it.
        if not promoted and re.match(rf"^local\s+{name}\b", line):
            line = re.sub(rf"^local\s+{name}\b", name, line, count=1)
            promoted = True
        lines.append(line)

    if not promoted:
        raise SystemExit(f"{rel}: no `local {name}` declaration found to promote")

    parts.append(f"-- ---- {rel} ----\n" + "\n".join(lines))

parts.append((root / "tests/assertions.luau").read_text())
out.write_text("\n\n".join(parts))
print(f"generated {out}")
PY

exec "$LUAU" "$OUT"
